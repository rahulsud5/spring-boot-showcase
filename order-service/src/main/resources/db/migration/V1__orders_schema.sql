-- =============================================================================
-- V1: core schema for order-service (PostgreSQL 17)
-- =============================================================================
-- Flyway applies V<version>__<description>.sql files in order, ONCE each, and records them (with a
-- checksum) in flyway_schema_history. NEVER edit an applied migration: add a new one. Every
-- environment then has exactly the same schema history.
--
-- Hibernate is configured with ddl-auto=validate: it CHECKS that the entities match this schema at
-- startup but never changes it. Schema changes are code-reviewed SQL, not ORM guesses.
--
-- The index design is explained in detail in docs/05-database-indexes-and-queries.md
-- =============================================================================

-- pg_trgm: trigram matching, which makes  ILIKE '%term%'  and similarity() searches indexable
CREATE EXTENSION IF NOT EXISTS pg_trgm;

-- -----------------------------------------------------------------------------
-- CUSTOMERS
-- -----------------------------------------------------------------------------
CREATE TABLE customers (
    id          varchar(64)  PRIMARY KEY,                 -- = the OAuth2 "sub" claim
    email       varchar(320) NOT NULL,
    full_name   varchar(200) NOT NULL,
    tier        varchar(16)  NOT NULL DEFAULT 'STANDARD'
                CHECK (tier IN ('STANDARD', 'SILVER', 'GOLD')),
    referred_by varchar(64)  REFERENCES customers (id),   -- self-reference: a referral TREE (see the recursive CTE)
    created_at  timestamptz  NOT NULL DEFAULT now(),
    deleted_at  timestamptz                               -- soft delete
);

-- PARTIAL + EXPRESSION + UNIQUE index, three ideas in one line:
--   lower(email)              case-insensitive uniqueness: "Ann@x.com" collides with "ann@x.com"
--   WHERE deleted_at IS NULL  only ACTIVE customers must be unique, so a deleted account frees its email
--   Queries must use the SAME expression to hit it:  WHERE lower(email) = lower(:email) AND deleted_at IS NULL
CREATE UNIQUE INDEX ux_customers_email_active
    ON customers (lower(email))
    WHERE deleted_at IS NULL;

-- GIN TRIGRAM index: fuzzy name search.  WHERE full_name ILIKE '%smi%'  becomes an index scan instead
-- of a full table scan. (A plain B-tree can only serve prefix searches like 'smi%'.)
CREATE INDEX ix_customers_full_name_trgm
    ON customers USING gin (full_name gin_trgm_ops);

-- Partial index on a sparse foreign key: most customers have no referrer, so don't index the NULLs
CREATE INDEX ix_customers_referred_by
    ON customers (referred_by)
    WHERE referred_by IS NOT NULL;

-- -----------------------------------------------------------------------------
-- ORDERS
-- -----------------------------------------------------------------------------
CREATE TABLE orders (
    id                   uuid          PRIMARY KEY,       -- UUIDv7 generated by the app (time-ordered, index-friendly)
    customer_id          varchar(64)   NOT NULL REFERENCES customers (id),
    status               varchar(16)   NOT NULL
                         CHECK (status IN ('PENDING', 'CONFIRMED', 'SHIPPED', 'DELIVERED', 'CANCELLED')),
    total_amount         numeric(12,2) NOT NULL CHECK (total_amount >= 0),   -- NEVER float/double for money
    discount_amount      numeric(12,2) NOT NULL DEFAULT 0 CHECK (discount_amount >= 0),
    currency             char(3)       NOT NULL,                             -- ISO 4217
    shipping_street      varchar(200)  NOT NULL,
    shipping_city        varchar(100)  NOT NULL,
    shipping_postal_code varchar(20)   NOT NULL,
    shipping_country     char(2)       NOT NULL,                             -- ISO 3166-1 alpha-2
    cancellation_reason  varchar(500),
    metadata             jsonb         NOT NULL DEFAULT '{}'::jsonb,         -- flexible attributes: channel, campaign, device...
    version              bigint        NOT NULL DEFAULT 0,                   -- JPA @Version: optimistic locking
    created_at           timestamptz   NOT NULL,
    updated_at           timestamptz   NOT NULL,
    created_by           varchar(64),
    CONSTRAINT ck_orders_cancel_reason CHECK (status <> 'CANCELLED' OR cancellation_reason IS NOT NULL)
);

-- COMPOSITE B-TREE built for the "my orders" screen, which uses KEYSET pagination:
--     WHERE customer_id = ? AND (created_at, id) < (?, ?) ORDER BY created_at DESC, id DESC LIMIT 20
-- Column order rule: EQUALITY columns first (customer_id), then the SORT/RANGE columns, in the same
-- direction as the ORDER BY. Postgres then reads exactly 20 index entries: no sort, no OFFSET scan.
-- It also makes the FK customer_id fast for joins and for ON DELETE checks.
CREATE INDEX ix_orders_customer_created
    ON orders (customer_id, created_at DESC, id DESC);

-- COVERING index (INCLUDE): the operations dashboard
--     SELECT status, created_at, total_amount, currency FROM orders WHERE status = ? AND created_at >= ?
-- can be answered by an INDEX-ONLY SCAN, without visiting the table heap at all. INCLUDE columns are
-- stored in the leaf pages but are NOT part of the search key, so they don't affect ordering or
-- uniqueness.
CREATE INDEX ix_orders_status_created_covering
    ON orders (status, created_at)
    INCLUDE (total_amount, currency);

-- PARTIAL index: background jobs only ever look at ACTIVE orders (a small fraction of all rows). The
-- index stays small, hot in memory, and cheap to maintain because DELIVERED/CANCELLED rows aren't in it.
-- The query's WHERE must imply the index predicate: ... WHERE status IN ('PENDING','CONFIRMED') ...
CREATE INDEX ix_orders_active_created
    ON orders (created_at)
    WHERE status IN ('PENDING', 'CONFIRMED');

-- GIN on JSONB with jsonb_path_ops: a smaller and faster index that supports containment (@>) queries
--     WHERE metadata @> '{"channel": "mobile"}'
-- (Use the default jsonb_ops if you also need the key-existence operators ?, ?|, ?&.)
CREATE INDEX ix_orders_metadata
    ON orders USING gin (metadata jsonb_path_ops);

-- EXPRESSION index on a JSONB field that's queried with equality and sorted on:
--     WHERE metadata ->> 'campaign' = 'black-friday'
CREATE INDEX ix_orders_campaign
    ON orders ((metadata ->> 'campaign'))
    WHERE metadata ? 'campaign';

-- -----------------------------------------------------------------------------
-- ORDER LINES
-- -----------------------------------------------------------------------------
-- A SEQUENCE incremented by 50 matches Hibernate's pooled optimizer (allocationSize = 50): Hibernate
-- reserves 50 ids per round trip AND can batch INSERTs. (IDENTITY columns disable JDBC insert batching
-- in Hibernate, because it must read each generated id back immediately.)
CREATE SEQUENCE order_lines_seq START WITH 1 INCREMENT BY 50;

CREATE TABLE order_lines (
    id          bigint        PRIMARY KEY,
    order_id    uuid          NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    line_no     smallint      NOT NULL,
    sku         varchar(64)   NOT NULL,
    quantity    integer       NOT NULL CHECK (quantity > 0),
    unit_amount numeric(12,2) NOT NULL CHECK (unit_amount >= 0),
    currency    char(3)       NOT NULL,
    CONSTRAINT ux_order_lines_order_line UNIQUE (order_id, line_no)
);
-- NOTE: PostgreSQL does NOT index foreign keys automatically. Here the UNIQUE (order_id, line_no)
-- constraint already creates an index whose LEFTMOST column is order_id, so it serves
-- "WHERE order_id = ?" and the FK checks. A separate index on order_id would be REDUNDANT: it costs
-- write performance and storage for no gain. Review indexes for leftmost-prefix redundancy!

-- "Which orders contain SKU X?" for product analytics and the GraphQL filter
CREATE INDEX ix_order_lines_sku
    ON order_lines (sku);

-- -----------------------------------------------------------------------------
-- STATUS HISTORY: maintained by a TRIGGER, so it's recorded even for updates made outside the
-- application (manual fixes, scripts)
-- -----------------------------------------------------------------------------
CREATE TABLE order_status_history (
    id          bigint      GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    order_id    uuid        NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    from_status varchar(16),
    to_status   varchar(16) NOT NULL,
    changed_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_order_status_history_order
    ON order_status_history (order_id, changed_at);

-- BRIN (Block Range INdex): for huge, APPEND-ONLY tables where the value correlates with the physical
-- row order (timestamps of inserted rows). It stores only min/max per range of pages, so it's about
-- 1000x smaller than a B-tree, ideal for "WHERE changed_at BETWEEN ... AND ..." on hundreds of
-- millions of rows. Useless when the data isn't physically ordered by that column.
CREATE INDEX brin_order_status_history_changed_at
    ON order_status_history USING brin (changed_at);

CREATE FUNCTION record_order_status_change() RETURNS trigger
    LANGUAGE plpgsql AS
$$
BEGIN
    IF TG_OP = 'INSERT' THEN
        INSERT INTO order_status_history (order_id, from_status, to_status) VALUES (NEW.id, NULL, NEW.status);
    ELSIF NEW.status IS DISTINCT FROM OLD.status THEN
        INSERT INTO order_status_history (order_id, from_status, to_status) VALUES (NEW.id, OLD.status, NEW.status);
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_orders_status_history
    AFTER INSERT OR UPDATE OF status ON orders
    FOR EACH ROW EXECUTE FUNCTION record_order_status_change();

-- -----------------------------------------------------------------------------
-- AUDIT LOG: written with REQUIRES_NEW transactions (it survives rollbacks of the business tx)
-- -----------------------------------------------------------------------------
CREATE TABLE audit_log (
    id          bigint      GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    action      varchar(64) NOT NULL,
    principal   varchar(64),
    details     jsonb       NOT NULL DEFAULT '{}'::jsonb,
    occurred_at timestamptz NOT NULL DEFAULT now()
);
-- BRIN with smaller ranges = more precise pruning at a (still tiny) size cost
CREATE INDEX brin_audit_log_occurred_at
    ON audit_log USING brin (occurred_at) WITH (pages_per_range = 32);
